"""Крок 2: Групування за однією колонкою та агрегація"""

# 1. Загальний дохід за типами напоїв
revenue_by_coffee = df.groupby('coffee_name')['money'].sum()
print("Загальний дохід за напоями:")
print(revenue_by_coffee)

# 2. Середня сума транзакції для кожного напою
avg_money = df.groupby('coffee_name')['money'].mean()
print("\nСередня сума транзакції:")
print(avg_money)

"""Крок 3: Групування за кількома колонками та скидання індексу"""

# Групування за 'Date' та 'coffee_name' з перетворенням у DataFrame
trans_count_df = df.groupby(['Date', 'coffee_name']).size().reset_index(name='count')

print(trans_count_df.head(10))

"""Крок 4: Використання agg для кількох агрегатних функцій"""

# Одночасне застосування кількох функцій до колонки 'money'
summary = df.groupby('coffee_name')['money'].agg(['sum', 'mean', 'min', 'max'])
print(summary)

"""Крок 5: Побудова зведеної таблиці"""

# Будуємо зведену таблицю, використовуючи наявну колонку 'Weekdaysort'
pivot = pd.pivot_table(
    df,
    values='money',
    index='coffee_name',
    columns='Weekdaysort',
    aggfunc='sum',
    fill_value=0
)
print(pivot)

"""Крок 6: Побудова перехресної таблиці"""

# Побудова перехресної таблиці
crosstab = pd.crosstab(df['coffee_name'], df['cash_type'])
print(crosstab)

"""Крок 7: Об'єднання даних за допомогою merge"""

# Створюємо довідковий DataFrame з категоріями
categories = pd.DataFrame({
    'coffee_name': ['Latte', 'Americano', 'Hot Chocolate', 'Cappuccino'],
    'category': ['молочний', 'чорний', 'молочний', 'молочний']
})

# З'єднуємо за допомогою merge
df_merged = df.merge(categories, on='coffee_name', how='left')
print(df_merged.head())

"""Крок 8: Об'єднання даних за допомогою concat"""

# Розбиваємо за колонкою 'Date'
df_part1 = df[df['Date'] <= '2024-03-15']
df_part2 = df[df['Date'] > '2024-03-15']

# Склеюємо через concat
df_concat = pd.concat([df_part1, df_part2])
print(f"Розміри: {len(df_part1)} + {len(df_part2)} = {len(df_concat)}")

"""Крок 9: Об'єднання за допомогою join"""

left = pd.DataFrame({'A': [1, 2, 3]}, index=['a', 'b', 'c'])
right = pd.DataFrame({'B': [10, 20, 30]}, index=['a', 'b', 'c'])

joined = left.join(right)
print(joined)

"""Крок 10: Обчислення частки доходу за напоями"""

total_revenue = df['money'].sum()
revenue_share = (df.groupby('coffee_name')['money'].sum() / total_revenue * 100).round(2)

