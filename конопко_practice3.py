# Синтетичні дані
data_messy = {
    'name': ['Anna', None, 'Bohdan', 'Olena', None],
    'age': [20, 21, None, 22, 24],
    'score': [85.5, 90.0, 78.3, None, 92.1]
}
df_messy = pd.DataFrame(data_messy)

# Підрахунок пропусків
print("Кількість пропусків:\n", df_messy.isnull().sum())

# Видалення рядків з пропусками у колонці 'name'
df_dropped = df_messy.dropna(subset=['name'])

# Заповнення пропусків у колонці 'age' середнім значенням
mean_age = df_messy['age'].mean()
df_filled = df_messy.copy()
df_filled['age'] = df_filled['age'].fillna(mean_age)

print("\nПісля заповнення age середнім:\n", df_filled)

data_dup = {
    'id': [1, 2, 3, 2, 3],
    'value': ['A', 'B', 'C', 'B', 'C']
}
df_dup = pd.DataFrame(data_dup)

# Виявлення та підрахунок дублікатів
print(df_dup.duplicated())
print("Кількість дублікатів:", df_dup.duplicated().sum())

# Видалення дублікатів (залишається перше входження)
df_unique = df_dup.drop_duplicates()
print("\nУнікальні рядки:\n", df_unique)

col_name = 'Total Revenue'

Q1 = df[col_name].quantile(0.25)
Q3 = df[col_name].quantile(0.75)
IQR = Q3 - Q1
lower = Q1 - 1.5 * IQR
upper = Q3 + 1.5 * IQR

print(f"Q1 = {Q1}, Q3 = {Q3}, IQR = {IQR}")
print(f"Нижня межа: {lower}, Верхня межа: {upper}")

outliers = df[(df[col_name] < lower) | (df[col_name] > upper)]
print(f"Знайдено викидів: {len(outliers)}")

# Перевірка типів до перетворення
print("Типи до перетворення:\n", df.dtypes, "\n")

# Перетворення Order Date на datetime64 (замініть 'Order Date', якщо назва інша)
df['Order Date'] = pd.to_datetime(df['Order Date'], errors='coerce')

# Перевірка типів після перетворення
print("Типи після перетворення:\n", df.dtypes)

df_text = pd.DataFrame({
    'country': [' Australia and Ocean ', 'CANADA', ' united states ', 'GERMANY', ' ukraine'],
    'order_code': ['ORD-123-A', 'ORD-234-B', 'ORD-345-C', 'ORD-456-D', 'ORD-123-A']
})

# Очищення: видалення пробілів по краях та приведення до нижнього регістру
df_text['country'] = df_text['country'].str.strip().str.lower()
df_text['order_code'] = df_text['order_code'].str.replace('-', '', regex=True)

print(df_text)

df['date_only'] = df['Order Date'].dt.date
df['year'] = df['Order Date'].dt.year
df['month'] = df['Order Date'].dt.month
df['day'] = df['Order Date'].dt.day
df['day_of_week'] = df['Order Date'].dt.dayofweek

print(df[['Order Date', 'date_only', 'year', 'month', 'day', 'day_of_week']].head())

df_encoded = pd.get_dummies(df, columns=['Item Type'])
print(df_encoded.head())

col = 'Total Revenue'

# Нормалізація (MinMax до діапазону [0, 1])
df['revenue_norm'] = (df[col] - df[col].min()) / (df[col].max() - df[col].min())

df['revenue_std'] = (df[col] - df[col].mean()) / df[col].std()

# Перевірка результатів
print(df[[col, 'revenue_norm', 'revenue_std']].head())
print("Мінімум revenue_norm:", df['revenue_norm'].min())
print("Максимум revenue_norm:", df['revenue_norm'].max())
print("Середнє revenue_std:", df['revenue_std'].mean())
print("Стандартне відхилення revenue_std:", df['revenue_std'].std())

final_df = df[['Order Date', 'Region', 'Country', 'Item Type', 'Units Sold', 'Total Revenue', 'revenue_norm', 'revenue_std']]

final_df.to_csv('cleaned_sales_data.csv', index=False)
